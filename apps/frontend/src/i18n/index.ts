/** Legacy: returns the raw dict */
export function useI18nDict(lang: Lang) {
  return { t: translations[lang] ?? translations.FR }
}

/**
 * Component-friendly hook.
 * Returns t(key) that supports dot notation ('nav.plants' → 'nav_plants')
 * and falls back to FR then the key itself.
 * Lang is driven by setGlobalLang() called from App.vue — no circular dep.
 */
export function useI18n() {
  function t(key: string): string {
    const normalised = key.replace(/\./g, '_')
    const dict = translations[_globalLang.value] ?? translations.FR
    return (dict as Record<string, string>)[normalised]
      ?? (translations.FR as Record<string, string>)[normalised]
      ?? key
  }

  return { t }
}

