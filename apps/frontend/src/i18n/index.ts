/**
 * Component-friendly hook.
 * Returns t(key, params?) that supports dot notation ('nav.plants' → 'nav_plants')
 * and falls back to FR then the key itself.
 * Supports placeholder replacement (e.g., t('key', { n: 5 }))
 * Lang is driven by setGlobalLang() called from App.vue — no circular dep.
 */
export function useI18n() {
  function t(key: string, params?: Record<string, string | number>): string {
    const normalised = key.replace(/\./g, '_')
    const dict = translations[_globalLang.value] ?? translations.FR
    let value = (dict as Record<string, string>)[normalised]
      ?? (translations.FR as Record<string, string>)[normalised]
      ?? key
    
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        value = value.replaceAll(`{${k}}`, String(v))
      })
    }
    return value
  }

  return { t }
}

